//! Position seed and 48-bit SingleThreadedRandomSource used by block models.
//! Arithmetic deliberately follows Java's wrapping int/long operations.
pub fn position_seed([x, y, z]: [i32; 3]) -> i64 {
    let seed = x.wrapping_mul(3129871) as i64 ^ (z as i64).wrapping_mul(116129781) ^ y as i64;
    seed.wrapping_mul(seed)
        .wrapping_mul(42317861)
        .wrapping_add(seed.wrapping_mul(11))
        >> 16
}
pub struct ModelRandom(u64);
impl ModelRandom {
    pub fn new(seed: i64) -> Self {
        Self((seed as u64 ^ 25214903917) & ((1 << 48) - 1))
    }
    fn next(&mut self, bits: u32) -> i32 {
        self.0 = self.0.wrapping_mul(25214903917).wrapping_add(11) & ((1 << 48) - 1);
        (self.0 >> (48 - bits)) as i32
    }
    pub fn next_long(&mut self) -> i64 {
        ((self.next(32) as i64) << 32).wrapping_add(self.next(32) as i64)
    }
    pub fn bounded(&mut self, bound: i32) -> i32 {
        assert!(bound > 0);
        if (bound as u32).is_power_of_two() {
            return ((bound as i64 * self.next(31) as i64) >> 31) as i32;
        }
        loop {
            let bits = self.next(31);
            let value = bits % bound;
            if bits.wrapping_sub(value).wrapping_add(bound - 1) >= 0 {
                return value;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn seeds_and_random_draws_match_official_26_2_classes() {
        // Generated by Mth.getSeed + SingleThreadedRandomSource from the
        // SHA-1-verified official JAR. The last bound exercises rejection.
        for (position, seed, child, draws) in [
            ([0, 0, 0], 0, -4962768465676381896, [2, 2, 516548029]),
            (
                [1, 64, -1],
                51075559105168,
                -7656025847503286258,
                [2, 6, 97681854],
            ),
            (
                [-30000000, -64, 30000000],
                -36386240128100,
                4085448494266116610,
                [0, 0, 810073714],
            ),
            (
                [i32::MAX, i32::MAX, i32::MIN],
                -90591246338681,
                8634142443761181808,
                [1, 3, 609636813],
            ),
        ] {
            assert_eq!(position_seed(position), seed);
            assert_eq!(ModelRandom::new(seed).next_long(), child);
            let mut random = ModelRandom::new(seed);
            assert_eq!(
                [
                    random.bounded(4),
                    random.bounded(7),
                    random.bounded(1073741825)
                ],
                draws
            );
        }
    }
}
